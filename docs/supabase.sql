-- ---------- REAKSI ARTIKEL ----------
-- Satu reaksi per user LOGIN per artikel (partial unique index user_id+article_id).
-- reaction: LIKE (suka) | WOW | FUNNY | SAD — ganti reaksi = UPDATE, klik lagi = hapus.
-- user_id NULL = reaksi anonim (tanpa login). Diduplikasi per session browser (session_id).
create table if not exists public.article_reactions (
  user_id    uuid references public.profiles (id) on delete cascade,
  article_id bigint not null references public.articles (id) on delete cascade,
  reaction   text not null check (reaction in ('LIKE','WOW','FUNNY','SAD')),
  session_id text,
  created_at timestamptz not null default now(),
  primary key (user_id, article_id)
);

-- Migrasi: reaksi kini boleh anonim.
-- Kolom PK tak boleh NULL, maka PK (user_id, article_id) dilepas dan diganti
-- partial unique index — dedup untuk user login (user_id) & pengunjung anonim (session_id).
alter table public.article_reactions drop constraint if exists article_reactions_pkey;
alter table public.article_reactions alter column user_id drop not null;
alter table public.article_reactions add column if not exists session_id text;
create unique index if not exists article_reactions_user_article_uniq
  on public.article_reactions (user_id, article_id) where user_id is not null;
create unique index if not exists article_reactions_session_article_uniq
  on public.article_reactions (session_id, article_id) where session_id is not null;

-- Mutasi reaksi lewat satu RPC atomik (security definer): ganti reaksi = UPDATE, klik lagi = hapus.
-- User login diidentifikasi user_id; anonim diidentifikasi session_id (localStorage browser).
-- ponytail: session_id tidak terkait IP/device — hapus localStorage berarti dapat reaksi lagi;
--           ganti ke identitas per-IP (edge function) bila perlu akurasi ketat.
create or replace function public.set_article_reaction(p_article_id bigint, p_reaction text, p_session_id text)
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_existing text;
begin
  if p_reaction not in ('LIKE','WOW','FUNNY','SAD') then
    return null;
  end if;
  if v_user_id is not null then
    select reaction into v_existing from public.article_reactions
      where article_id = p_article_id and user_id = v_user_id;
    if v_existing is null then
      insert into public.article_reactions (user_id, article_id, reaction)
      values (v_user_id, p_article_id, p_reaction);
      return 'added';
    elsif v_existing = p_reaction then
      delete from public.article_reactions where article_id = p_article_id and user_id = v_user_id;
      return 'removed';
    else
      update public.article_reactions set reaction = p_reaction
        where article_id = p_article_id and user_id = v_user_id;
      return 'updated';
    end if;
  else
    if p_session_id is null or p_session_id = '' then
      return null;
    end if;
    select reaction into v_existing from public.article_reactions
      where article_id = p_article_id and session_id = p_session_id;
    if v_existing is null then
      insert into public.article_reactions (user_id, article_id, reaction, session_id)
      values (null, p_article_id, p_reaction, p_session_id);
      return 'added';
    elsif v_existing = p_reaction then
      delete from public.article_reactions where article_id = p_article_id and session_id = p_session_id;
      return 'removed';
    else
      update public.article_reactions set reaction = p_reaction
        where article_id = p_article_id and session_id = p_session_id;
      return 'updated';
    end if;
  end if;
end;
$$;
grant execute on function public.set_article_reaction(bigint, text, text) to anon, authenticated;

-- Reaksi milik pengunjung saat ini (login → user_id, anonim → session_id).
create or replace function public.my_article_reaction(p_article_id bigint, p_session_id text)
returns text
language sql
security definer set search_path = public
as $$
  select reaction from public.article_reactions
  where article_id = p_article_id
    and (user_id = auth.uid() or (user_id is null and session_id = p_session_id))
  limit 1;
$$;
grant execute on function public.my_article_reaction(bigint, text) to anon, authenticated;

