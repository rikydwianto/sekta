-- Profil dibuat otomatis saat user mendaftar via Supabase Auth
-- Username diunifikasi dengan suffix bila sudah dipakai (hindari gagal insert)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  base_name     text;
  base_username text;
  username      text;
  suffix        integer := 0;
begin
  base_name := coalesce(new.raw_user_meta_data->>'full_name', '');
  -- email bisa null pada OAuth (Google); fallback '' agar NOT NULL username tak gagal
  base_username := coalesce(new.raw_user_meta_data->>'username', split_part(coalesce(new.email, ''), '@', 1));
  base_username := lower(regexp_replace(base_username, '[^a-z0-9_]', '', 'g'));
  username := base_username;
  loop
    begin
      insert into public.profiles (id, name, username, avatar)
      values (new.id, base_name, username, coalesce(new.raw_user_meta_data->>'avatar_url', new.raw_user_meta_data->>'picture', ''))
      on conflict (id) do nothing;
      exit;
    exception when unique_violation then
      suffix := suffix + 1;
      username := base_username || suffix;
    end;
  end loop;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Update otomatis kolom updated_at (profiles & articles)
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

drop trigger if exists articles_set_updated_at on public.articles;
create trigger articles_set_updated_at
  before update on public.articles
  for each row execute function public.set_updated_at();

-- Tambah penghitung baca artikel. Dipakai dari load halaman artikel (SSR & client).
-- Security definer agar anon/authenticated boleh menaikkan tanpa policy update (RLS update hanya penulis).
-- ponytail: view_count naik setiap load (termasuk refresh & bot); dedup via cookie bila angka harus akurat.
create or replace function public.increment_article_view(aid bigint)
returns void
language sql
security definer set search_path = public
as $$
  update public.articles set view_count = view_count + 1 where id = aid;
$$;
grant execute on function public.increment_article_view(bigint) to anon, authenticated;


-- Set published_at otomatis saat artikel pertama kali di-PUBLISH
create or replace function public.articles_set_published_at()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'PUBLISHED' and new.published_at is null then
    new.published_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists articles_set_published_at on public.articles;
create trigger articles_set_published_at
  before insert or update on public.articles
  for each row execute function public.articles_set_published_at();

